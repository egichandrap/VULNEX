package templates

import (
	"embed"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/vulnex/vulnex/installer/internal/domain"
)

//go:embed assets/*
var assetsFS embed.FS

// Generator materializes deployment specifications from embedded assets.
type Generator struct{}

func NewGenerator() *Generator {
	return &Generator{}
}

// Render writes docker-compose.yml, .env, and auxiliary configs into targetDir.
func (g *Generator) Render(cfg *domain.InstallConfig, targetDir string) error {
	cleanDir := filepath.Clean(targetDir)
	if err := os.MkdirAll(cleanDir, 0700); err != nil {
		return domain.WrapError(domain.ExitGeneralFailure, "failed to create deployment directory", err)
	}

	// 1. Render Compose File
	var composeSrc string
	if cfg.Mode == domain.DeploymentModeServer {
		composeSrc = "assets/docker-compose.server.yml"
	} else {
		composeSrc = "assets/docker-compose.local.yml"
	}

	composeData, err := assetsFS.ReadFile(composeSrc)
	if err != nil {
		return domain.WrapError(domain.ExitGeneralFailure, "failed to read embedded compose template", err)
	}

	composeDest := filepath.Join(cleanDir, "docker-compose.yml")
	if err := os.WriteFile(composeDest, composeData, 0600); err != nil {
		return domain.WrapError(domain.ExitGeneralFailure, "failed to write docker-compose.yml", err)
	}

	// 2. Render init.sql (Database schema)
	initData, err := assetsFS.ReadFile("assets/init.sql")
	if err == nil {
		initDest := filepath.Join(cleanDir, "init.sql")
		if err := os.WriteFile(initDest, initData, 0600); err != nil {
			return domain.WrapError(domain.ExitGeneralFailure, "failed to write init.sql", err)
		}
	}

	// 3. Render Caddyfile (if Server mode with Embedded Caddy)
	if cfg.Mode == domain.DeploymentModeServer && cfg.Ingress == domain.IngressEmbeddedCaddy {
		caddyData, err := assetsFS.ReadFile("assets/Caddyfile")
		if err != nil {
			return domain.WrapError(domain.ExitGeneralFailure, "failed to read embedded Caddyfile", err)
		}

		caddyDir := filepath.Join(cleanDir, "caddy")
		if err := os.MkdirAll(caddyDir, 0700); err != nil {
			return domain.WrapError(domain.ExitGeneralFailure, "failed to create caddy directory", err)
		}

		caddyDest := filepath.Join(caddyDir, "Caddyfile")
		if err := os.WriteFile(caddyDest, caddyData, 0600); err != nil {
			return domain.WrapError(domain.ExitGeneralFailure, "failed to write Caddyfile", err)
		}
	}

	// 3. Render .env
	var envBuilder strings.Builder
	envBuilder.WriteString("# Generated by VULNEX Installer\n")
	envBuilder.WriteString("POSTGRES_DB=vulnex\n")
	envBuilder.WriteString("POSTGRES_USER=vulnex\n")
	envBuilder.WriteString(fmt.Sprintf("POSTGRES_PASSWORD=%s\n", cfg.DatabasePassword))
	if cfg.DomainName != "" {
		envBuilder.WriteString(fmt.Sprintf("DOMAIN=%s\n", cfg.DomainName))
	}
	version := cfg.Version
	if version == "" {
		version = "1.0.0"
	}
	envBuilder.WriteString(fmt.Sprintf("VULNEX_VERSION=%s\n", version))
	if cfg.TrustedProxies != "" {
		envBuilder.WriteString(fmt.Sprintf("TRUSTED_PROXIES=%s\n", cfg.TrustedProxies))
	}

	envDest := filepath.Join(cleanDir, ".env")
	if err := os.WriteFile(envDest, []byte(envBuilder.String()), 0600); err != nil {
		return domain.WrapError(domain.ExitGeneralFailure, "failed to write .env file", err)
	}

	return nil
}
